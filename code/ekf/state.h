#pragma once
// ============================================================================
//  state.h —— 状态向量定义 & 装甲板几何常量
//  严格对应 PPT 第 14 页的整车状态向量 x：
//      x = [ c_x, c_y, v_x, v_y, z_a, v_z, θ, ω, r ]ᵀ      (9 维)
//  含义：
//      c_x, c_y : 车中心在“观察者基坐标系”下的地面位置(米)
//      v_x, v_y : 车中心地面速度(米/秒)
//      z_a      : 装甲板离地高度(米) —— 简化模型四块板共用同一高度
//      v_z      : 高度方向速度(米/秒)
//      θ        : 车头朝向(绕世界 z 轴，弧度)，决定四块板方位
//      ω        : 角速度(弧度/秒)，θ 的变化率
//      r        : 车中心到装甲板的水平半径(米)，由机器人尺寸决定
//
//  关于坐标系（重要，决定可观测性，详见报告“思考”一节）：
//      本作业数据是“同一台机器人内录”的相机+IMU，相机装在观察者(机器人)上。
//      我们定义“基坐标系”原点在观察者初始位置、轴随观察者初始朝向固定。
//      每帧用 IMU 偏航角把相机系观测旋转回基坐标系，从而估计“目标车相对观察者”
//      的状态——这样 c_x,c_y 是相对可观测的(目标相对观察者运动)。
// ============================================================================
#include <vector>
#include <cmath>
#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

// ---- 状态向量索引（写代码时用名字而非魔法数字，防止错位）----
enum StateIdx {
    IX_CX = 0,   // c_x
    IX_CY = 1,   // c_y
    IX_VX = 2,   // v_x
    IX_VY = 3,   // v_y
    IX_ZA = 4,   // z_a
    IX_VZ = 5,   // v_z
    IX_TH = 6,   // θ
    IX_OM = 7,   // ω
    IX_R  = 8    // r
};
static const int NX = 9;   // 状态维度

// ---- 装甲板几何常量（机器人标定/先验已知，不是要估计的状态）----
//  RM 标准步兵机器人四块装甲板分布在四个朝向，互成 90°：
//  φ_j : 第 j 块板相对车头的方位偏角（弧度）
//  r   : 车中心到板的水平距离（由机器人底盘半径决定，见状态 r）
//  z_a : 板离地高度（简化模型四块板同高，用状态 z_a 表示）
//
//  初始化为“四块板分别在 前/右/后/左”，与真实机器人一致。
//  若你的机器人尺寸不同，只需改这里两个常量即可。
static const int N_PLATES = 4;
// 四块板相对车头的方位偏角（前=0°, 右=90°, 后=180°, 左=270°）
static const double PLATE_PHI[N_PLATES] = {
    0.0,
    M_PI / 2.0,
    M_PI,
    3.0 * M_PI / 2.0
};
// 机器人底盘半径（车中心到装甲板），单位米。标准步兵约 0.25m。
static const double ROBOT_RADIUS = 0.25;

// 装甲板离地高度（米），标准步兵装甲板中心约 0.30m
static const double PLATE_HEIGHT = 0.30;

// 取状态向量（按索引）
static inline double& sx(std::vector<double>& x, int i) { return x[i]; }
static inline double  sx(const std::vector<double>& x, int i) { return x[i]; }
